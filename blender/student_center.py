"""Student centre: 2021 GXU film and 2022 architecture-association aerial.

The west tower terrace is one storey, not five. Mapped ground outline is retained;
the upper west return, setbacks and roof equipment are photo-scaled estimates.
The separately mapped historic tower is generated by student_water_tower.py.
"""
import math
from mathutils import Vector
from mathutils.geometry import tessellate_polygon
from geometry import Mesh, MATERIALS, material
from south_gate import inscription


def student_center_materials(C):
    """A local translucent guard pane; leave every existing material unchanged."""
    if 'studentRailGlass' not in C:
        index=material('studentRailGlass',(.35,.48,.46),.3,.05)
        mat=MATERIALS[index]
        mat.diffuse_color=(*mat.diffuse_color[:3],.28)
        mat.node_tree.nodes.get('Principled BSDF').inputs['Alpha'].default_value=.28
        mat.surface_render_method='DITHERED'
        mat.use_backface_culling=False
        C['studentRailGlass']=index


def ccw(ring):
    ring=list(ring[:-1] if ring[0]==ring[-1] else ring)
    if sum(a[0]*b[1]-b[0]*a[1] for a,b in zip(ring,ring[1:]+ring[:1]))<0:
        ring.reverse()
    return ring


def inset(ring,distance):
    """Mitered inward parallel curve for this smooth, simple mapped outline."""
    out=[]
    for i,p in enumerate(ring):
        a=ring[i-1];b=ring[(i+1)%len(ring)]
        u=Vector((p[0]-a[0],p[1]-a[1])).normalized()
        v=Vector((b[0]-p[0],b[1]-p[1])).normalized()
        shift=Vector((-u.y-v.y,u.x+v.x))*distance/(1+u.dot(v))
        out.append((p[0]+shift.x,p[1]+shift.y))
    return out


def upper_outline(b):
    # Follow the east/north/south mapped lobes; replace only the projecting west
    # terrace. The curved return is inferred from the aerial, not a measured plan.
    east=[p for p in ccw(b['polygons'][0][0]) if p[0]>=255.8]
    return_curve=[(253.2,33.5),(250.9,39),(249.2,45),
                  (248.7,51),(249.4,57),(251.2,63),(253.5,69)]
    ring=[]
    for a,c in zip(east,east[1:]+east[:1]):
        ring.append(a)
        if max(a[0],c[0])<257 and abs(c[1]-a[1])>30:
            ring.extend(return_curve if c[1]>a[1] else return_curve[::-1])
    return ring


def prism(m,ring,bottom,top,wall,cap):
    points=[Vector((x,y,top)) for x,y in ring]
    for tri in tessellate_polygon([points]):
        vertices=[tuple(points[p] if isinstance(p,int) else p) for p in tri]
        m.face(vertices,cap)
        m.face([(x,y,bottom) for x,y,_ in reversed(vertices)],wall)
    for a,b in zip(ring,ring[1:]+ring[:1]):
        m.face([(*a,bottom),(*b,bottom),(*b,top),(*a,top)],wall)


def edge(m,ring,z,depth,height,mat,closed=True):
    for a,b in zip(ring,ring[1:]+(ring[:1] if closed else [])):
        dx,dy=b[0]-a[0],b[1]-a[1]
        m.box((a[0]+b[0])/2,(a[1]+b[1])/2,z,math.hypot(dx,dy)+.03,
              depth,height,mat,math.atan2(dy,dx))


def railing(m,ring,z,C,detail,closed=True):
    edge(m,ring,z+.94,.065,.065,C['metal'],closed)
    edge(m,ring,z+.12,.045,.045,C['metal'],closed)
    for a,b in zip(ring,ring[1:]+(ring[:1] if closed else [])):
        dx,dy=b[0]-a[0],b[1]-a[1];length=math.hypot(dx,dy)
        m.face([(*a,z+.14),(*b,z+.14),(*b,z+.88),(*a,z+.88)],C['studentRailGlass'])
        n=max(1,math.ceil(length/(2.2 if detail else 4.4)))
        for j in range(n):
            t=j/n;m.box(a[0]+dx*t,a[1]+dy*t,z+.5,.055,.055,1,C['metal'])


def glazing(m,ring,bottom,top,C,detail):
    prism(m,ring,bottom,top,C['glass'],C['dark'])
    if not detail:return
    edge(m,ring,top-.65,.085,.075,C['dark'])
    for a,b in zip(ring,ring[1:]+ring[:1]):
        dx,dy=b[0]-a[0],b[1]-a[1];length=math.hypot(dx,dy)
        count=max(1,round(length/1.6))
        for j in range(count):
            t=j/count;m.box(a[0]+dx*t,a[1]+dy*t,(bottom+top)/2,
                             .10,.10,top-bottom,C['dark'])


def student_center(l,b,z,C,detail=True):
    m=Mesh();height=l['height'];floor=height/5
    outer=ccw(b['polygons'][0][0]);upper=upper_outline(b)
    ground=Mesh()
    # Ground glazing follows the mapped footprint with the tower void retained.
    # Use original triangulation only for the deck, never fill the circular hole.
    rings=b['polygons'][0];flat=[p for ring in rings for p in ring[:-1]]
    triangles=b['roofTriangles'][0]
    for i in range(0,len(triangles),3):
        ground.face([(*flat[k],z+floor) for k in triangles[i:i+3]],C['path'])
    for i,ring in enumerate(rings):
        boundary=ccw(ring)
        if i:boundary.reverse()
        for a,c in zip(boundary,boundary[1:]+boundary[:1]):
            ground.face([(*a,z),(*c,z),(*c,z+floor-.65),(*a,z+floor-.65)],C['glass'])
        edge(ground,boundary,z+floor-.42,.35,.84,C['white'])
    if detail:
        edge(ground,outer,z+.15,.12,.3,C['dark'])
        for a,c in zip(outer,outer[1:]+outer[:1]):
            n=max(1,round(math.dist(a,c)/1.6))
            for j in range(n):
                t=j/n;ground.box(a[0]+(c[0]-a[0])*t,a[1]+(c[1]-a[1])*t,
                                 z+(floor-.65)/2,.1,.1,floor-.65,C['dark'])
    # Only the exposed western platform has a first-floor terrace railing.
    terrace=[p for p in outer if p[0]<256]
    railing(ground,terrace,z+floor,C,detail,closed=False)
    m.add_part('西侧一层水塔平台与首层曲面玻璃',ground)

    floors=Mesh()
    glass_outline=inset(upper,1.35)
    for f in range(1,5):
        bottom=z+f*floor;top=z+(f+1)*floor
        prism(floors,upper,bottom-.84,bottom,C['white'],C['path'])
        glazing(floors,glass_outline,bottom,top-.84,C,detail)
        railing(floors,inset(upper,.22),bottom,C,detail)
    prism(floors,upper,z+height-1.15,z+height,C['white'],C['paleRoof'])
    railing(floors,inset(upper,.25),z+height,C,detail)
    m.add_part('四层上部曲面阳台、内退玻璃与平屋顶',floors)

    roof=Mesh()
    # Two white service rooms, a glazed plant box and parallel collector banks
    # are visible at 00:31 in BV1US4y1V7dg. Positions/dimensions remain estimated.
    for x,y,w,d,h in [(269,54,11,8,3.1),(307,40,12,9,3.3)]:
        roof.box(x,y,z+height+h/2,w,d,h,C['white'])
        roof.box(x,y,z+height+h+.12,w+.35,d+.35,.24,C['white'])
        roof.box(x,y-d/2-.03,z+height+1.3,1.4,.08,2.6,C['dark'])
    roof.box(281,43,z+height+1.7,6,6,3.4,C['dark'])
    if detail:
        for x in [278.1,279.5,281,282.5,283.9]:
            roof.box(x,39.95,z+height+1.7,.08,.1,3.4,C['metal'])
        for zz in [0,1.7,3.4]:roof.box(281,39.95,z+height+zz,6,.1,.08,C['metal'])
    for row in range(5):
        yy=52+row*2.8
        for col in range(8):
            xx=282+col*1.9
            roof.face([(xx,yy,z+height+.55),(xx+1.75,yy,z+height+.55),
                       (xx+1.75,yy+1.8,z+height+1.15),(xx,yy+1.8,z+height+1.15)],C['libraryInk'])
            if detail:
                roof.line((xx,yy,z+height+.55),(xx+1.75,yy,z+height+.55),.035,C['metal'])
    sign=inscription('大学生活动中心',305,12,z+height+2.4,21,2.6,C['red'],detail)
    roof.extend(sign)
    for x in [295,298,301,304,307,310,313,316]:
        roof.box(x,12.2,z+height+1.75,.09,.09,3.5,C['metal'])
        roof.line((x,12.2,z+height+2.8),(x,15,z+height),.05,C['metal'])
    m.add_part('屋顶设备房、采集板与红色校名',roof)
    return m
